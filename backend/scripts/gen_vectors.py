"""Generate known-answer vectors for LR-CRASH-1 from the Python reference implementation.

Usage: uv run python scripts/gen_vectors.py [--check]
Writes contracts/math/lr-crash-1/vectors.json. With --check, exits 1 if the committed file
differs from what the reference implementation produces (run in CI).
"""

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from luxrocket.core import curve, multiplier, outcome

OUT = Path(__file__).resolve().parents[2] / "contracts" / "math" / "lr-crash-1" / "vectors.json"
EDGE_BP = 300
MAX_X10000 = 100_000_000
D = outcome.D


def h(label: str) -> bytes:
    return hashlib.sha256(label.encode()).digest()


def build() -> dict[str, object]:
    salt = h("luxrocket-kat-salt")
    table = curve.generate_table(curve.DEFAULT_LAMBDA_PER_MS, MAX_X10000)

    # Boundary values of r around the instant-crash threshold and the cap.
    def r_for_raw_at_least(k: int) -> int:
        # smallest r with raw >= k: r >= D - 100*(1-e)*D/k  (ceil)
        num = 100 * (10_000 - EDGE_BP) * D
        return D - (num // (10_000 * k))

    edge_rs = sorted(
        {
            0,
            1,
            D - 1,
            D // 2,
            D - 2,
            r_for_raw_at_least(101) - 1,
            r_for_raw_at_least(101),
            r_for_raw_at_least(200) - 1,
            r_for_raw_at_least(200),
            r_for_raw_at_least(MAX_X10000 // 100) - 1,
            r_for_raw_at_least(MAX_X10000 // 100),
        }
    )
    r_vectors = [
        {"r": str(r), "crash_x10000": outcome.crash_from_r(r, EDGE_BP, MAX_X10000)}
        for r in edge_rs
        if 0 <= r < D
    ]

    seed_vectors = []
    for i in range(200):
        seed = h(f"luxrocket-kat-seed-{i}")
        rh = outcome.round_hash(seed, salt)
        seed_vectors.append(
            {
                "seed": seed.hex(),
                "round_hash": rh.hex(),
                "r": str(outcome.first_52_bits(rh)),
                "crash_x10000": outcome.crash_from_seed(seed, salt, EDGE_BP, MAX_X10000),
            }
        )

    chain = [h("luxrocket-kat-chain-root")]
    for _ in range(10):
        chain.append(outcome.chain_next(chain[-1]))

    sample_ts = [0, 1, 2, 3, 100, 1000, 11552, 11553, 50_000, 100_000, len(table) - 1]
    curve_samples = [{"t_ms": t, "multiplier_x10000": table[t]} for t in sample_ts]
    crash_times = [
        {"crash_x10000": c, "t_crash_ms": curve.crash_time_ms(table, c)}
        for c in [10_000, 10_100, 15_000, 20_000, 100_000, 1_000_000, MAX_X10000]
    ]

    payouts = [
        {
            "stake_minor": 500,
            "multiplier_x10000": 23_456,
            "max_win_minor": None,
            "payout_minor": multiplier.payout_minor(500, 23_456),
        },
        {
            "stake_minor": 1,
            "multiplier_x10000": 19_999,
            "max_win_minor": None,
            "payout_minor": multiplier.payout_minor(1, 19_999),
        },
        {
            "stake_minor": 1_000_000,
            "multiplier_x10000": 100_000_000,
            "max_win_minor": 1_000_000_00,
            "payout_minor": multiplier.payout_minor(1_000_000, 100_000_000, 1_000_000_00),
        },
    ]

    return {
        "formula_version": outcome.FORMULA_VERSION,
        "note": "Generated by backend/scripts/gen_vectors.py. Do not edit by hand.",
        "params": {
            "house_edge_bp": EDGE_BP,
            "max_multiplier_x10000": MAX_X10000,
            "curve_lambda_per_ms": curve.DEFAULT_LAMBDA_PER_MS,
            "curve_length": len(table),
            "curve_table_sha256": curve.table_hash(table),
            "curve_encoding": "int32 little-endian, index = ms since launch",
        },
        "salt": salt.hex(),
        "r_vectors": r_vectors,
        "seed_vectors": seed_vectors,
        "chain": [s.hex() for s in chain],
        "curve_samples": curve_samples,
        "crash_times": crash_times,
        "payouts": payouts,
    }


def main() -> int:
    data = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != data:
            print(f"{OUT} is out of date; run scripts/gen_vectors.py", file=sys.stderr)
            return 1
        print("vectors up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(data)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
